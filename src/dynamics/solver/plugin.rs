/// A units-per-meter scaling factor that adjusts the engine's internal properties
/// to the scale of the world.
///
/// For example, a 2D game might use pixels as units and have an average object size
/// of around 100 pixels. By setting the length unit to `100.0`, the physics engine
/// will interpret 100 pixels as 1 meter for internal thresholds, improving stability.
///
/// Note that this is *not* used to scale forces or any other user-facing inputs or outputs.
/// Instead, the value is only used to scale some internal length-based tolerances, such as
/// [`SleepingThreshold::linear`] and [`NarrowPhaseConfig::contact_tolerance`], as well as
/// the scale used for [debug rendering](PhysicsDebugPlugin).
///
/// Choosing the appropriate length unit can help improve stability and robustness.
///
/// Default: `1.0`
///
/// # Example
///
/// The [`PhysicsLengthUnit`] can be inserted as a resource like normal,
/// but it can also be specified through the [`PhysicsPlugins`] plugin group.
///
/// ```no_run
/// # #[cfg(feature = "2d")]
/// use avian2d::prelude::*;
/// use bevy::prelude::*;
///
/// # #[cfg(feature = "2d")]
/// fn main() {
///     App::new()
///         .add_plugins((
///             DefaultPlugins,
///             // A 2D game with 100 pixels per meter
///             PhysicsPlugins::default().with_length_unit(100.0),
///         ))
///         .run();
/// }
/// # #[cfg(not(feature = "2d"))]
/// # fn main() {} // Doc test needs main
/// ```
#[derive(Resource, Clone, Debug, Deref, DerefMut, PartialEq, Reflect)]
#[reflect(Resource)]
pub struct PhysicsLengthUnit(pub f32);

impl Default for PhysicsLengthUnit {
    fn default() -> Self {
        Self(1.0)
    }
}

/// Configuration parameters for the constraint solver that handles
/// things like contacts and joints.
///
/// These are tuned to give good results for most applications, but can
/// be configured if more control over the simulation behavior is needed.
#[derive(Resource, Clone, Debug, PartialEq, Reflect)]
#[reflect(Resource)]
pub struct SolverConfig {
    /// The damping ratio used for contact stabilization.
    ///
    /// Lower values make contacts more compliant or "springy",
    /// allowing more visible penetration before overlap has been
    /// resolved and the contact has been stabilized.
    ///
    /// Consider using a higher damping ratio if contacts seem too soft.
    /// Note that making the value too large can cause instability.
    ///
    /// Default: `10.0`.
    pub contact_damping_ratio: f32,

    /// Scales the frequency used for contacts. A higher frequency
    /// makes contact responses faster and reduces visible springiness,
    /// but can hurt stability.
    ///
    /// The solver computes the frequency using the time step and substep count,
    /// and limits the maximum frequency to be at most half of the time step due to
    /// [Nyquist's theorem](https://en.wikipedia.org/wiki/Nyquist%E2%80%93Shannon_sampling_theorem).
    /// This factor scales the resulting frequency, which can lead to unstable behavior
    /// if the factor is too large.
    ///
    /// Default: `1.5`
    pub contact_frequency_factor: f32,

    /// The maximum speed at which overlapping bodies are pushed apart by the solver.
    ///
    /// With a small value, overlap is resolved gently and gradually, while large values
    /// can result in more snappy behavior.
    ///
    /// This is implicitly scaled by the [`PhysicsLengthUnit`].
    ///
    /// Default: `4.0`
    pub max_overlap_solve_speed: f32,

    /// The coefficient in the `[0, 1]` range applied to
    /// [warm start](SubstepSolverSystems::WarmStart) impulses.
    ///
    /// Warm starting uses the impulses from the previous frame as the initial
    /// solution for the current frame. This helps the solver reach the desired
    /// state much faster, meaning that *convergence* is improved.
    ///
    /// The coefficient should typically be set to `1.0`.
    ///
    /// Default: `1.0`
    pub warm_start_coefficient: f32,

    /// The minimum speed along the contact normal in units per second
    /// for [restitution](Restitution) to be applied.
    ///
    /// An appropriate threshold should typically be small enough that objects
    /// keep bouncing until the bounces are effectively unnoticeable,
    /// but large enough that restitution is not applied unnecessarily,
    /// improving performance and stability.
    ///
    /// This is implicitly scaled by the [`PhysicsLengthUnit`].
    ///
    /// Default: `1.0`
    pub restitution_threshold: f32,

    /// The number of iterations used for applying [restitution](Restitution).
    ///
    /// A higher number of iterations can result in more accurate bounces,
    /// but it only makes a difference when there are more than one contact point.
    ///
    /// For example, with just one iteration, a cube falling flat on the ground
    /// might bounce and rotate to one side, because the impulses are applied
    /// to the corners sequentially, and some of the impulses are likely to be larger
    /// than the others. With multiple iterations, the impulses are applied more evenly.
    ///
    /// Default: `1`
    pub restitution_iterations: usize,

}

impl Default for SolverConfig {
    fn default() -> Self {
        Self {
            contact_damping_ratio: 10.0,
            contact_frequency_factor: 1.5,
            max_overlap_solve_speed: 4.0,
            warm_start_coefficient: 1.0,
            restitution_threshold: 1.0,
            restitution_iterations: 1,
        }
    }
}

/// Contact constraints invalidated by an authoritative topology change.
#[derive(Resource, Debug, Default)]
pub struct ContactReseolveQueue {
    pending: Vec<ContactId>,
    prepared_contacts: Option<Vec<ContactId>>,
    impulse_retention: HashMap<ContactId, f32>,
}

impl ContactReseolveQueue {
    /// Requests contacts for rollback and one local re-solve.
    pub fn request_contacts(
        &mut self,
        contact_ids: impl IntoIterator<Item = ContactId>,
    ) {
        self.pending.extend(contact_ids);
    }

    /// Requests a contact rebuild with a precomputed fraction of the applied
    /// impulse retained. Material failure and energy accounting belong to the
    /// caller; the solver only applies this scalar to its impulse ledger.
    pub fn request_impulse_retention(
        &mut self,
        contact_id: ContactId,
        retained_fraction: f32,
    ) -> f32 {
        if !retained_fraction.is_finite() {
            return 1.0;
        }

        let retained_fraction = retained_fraction.clamp(0.0, 1.0);
        self.request_contacts([contact_id]);
        let stored = self
            .impulse_retention
            .entry(contact_id)
            .and_modify(|current| *current = (*current).min(retained_fraction))
            .or_insert(retained_fraction);
        *stored
    }

    /// Returns the precomputed impulse fraction for a refreshed contact pair.
    pub(crate) fn retained_impulse_fraction(&self, contact_id: ContactId) -> Option<f32> {
        self.impulse_retention.get(&contact_id).copied()
    }

    /// Whether topology publication requires the standard collider refresh pipeline.
    pub(crate) fn has_pending_rebuild(&self) -> bool {
        !self.pending.is_empty()
    }

    /// Whether the refreshed constraints are ready for material configuration.
    pub fn has_prepared_re_solve(&self) -> bool {
        self.prepared_contacts.is_some()
    }

    /// Returns requested old constraints. The rollback stage reverses an
    /// impulse only if refreshed geometry provides a replacement manifold;
    /// impulses from contacts that fully disappeared remain committed.
    pub(crate) fn contacts_for_rollback(&mut self) -> Option<Vec<ContactId>> {
        if self.pending.is_empty() {
            return None;
        }
        self.pending.sort_unstable();
        self.pending.dedup();
        Some(self.pending.clone())
    }

    fn take_for_rebuild(&mut self) -> Option<Vec<ContactId>> {
        if self.pending.is_empty() {
            return None;
        }
        self.pending.sort_unstable();
        self.pending.dedup();
        let requested = core::mem::take(&mut self.pending);
        self.prepared_contacts = Some(requested.clone());
        self.impulse_retention.clear();
        Some(requested)
    }

    fn take_prepared_contacts(&mut self) -> Option<Vec<ContactId>> {
        core::mem::take(&mut self.prepared_contacts)
    }

    /// Discards any unconsumed transaction before the next solver substep.
    pub(crate) fn begin_substep(&mut self) {
        self.clear_pending();
    }

    fn clear_pending(&mut self) {
        self.pending.clear();
        self.prepared_contacts = None;
        self.impulse_retention.clear();
    }
}

/// A material contact whose configured normal impulse capacity was exceeded.
///
/// The event is emitted after the relaxation pass. The material owner updates
/// authoritative geometry, queues affected contacts before AABB refresh, and
/// lets the standard broad/narrow phase discover replacement manifolds.
#[derive(Message, Clone, Copy, Debug, PartialEq)]
pub struct ContactBreakEvent {
    /// The stable contact pair identifier.
    pub contact_id: ContactId,
    /// The first collider in the contact pair.
    pub collider1: Entity,
    /// The second collider in the contact pair.
    pub collider2: Entity,
    /// The first rigid body, if the collider is attached to one.
    pub body1: Option<Entity>,
    /// The second rigid body, if the collider is attached to one.
    pub body2: Option<Entity>,
    /// The configured capacity in impulse units.
    pub max_normal_impulse: f32,
    /// The largest requested normal impulse in the failed constraint points.
    pub requested_normal_impulse: f32,
    /// The world-space direction and magnitude of the requested normal impulse.
    ///
    /// In 3D this can be fed directly into a fragment momentum transfer model.
    pub requested_normal_impulse_vector: Vector,
}

/// The [`SoftnessCoefficients`] used for contacts.
///
/// **Note**: This resource is updated automatically and not intended to be modified manually.
/// Use the [`SolverConfig`] resource instead for tuning contact behavior.
#[derive(Resource, Clone, Copy, PartialEq, Reflect)]
#[reflect(Resource)]
pub struct ContactSoftnessCoefficients {
    /// The [`SoftnessCoefficients`] used for contacts against dynamic bodies.
    pub dynamic: SoftnessCoefficients,
    /// The [`SoftnessCoefficients`] used for contacts against static or kinematic bodies.
    pub non_dynamic: SoftnessCoefficients,
}

impl Default for ContactSoftnessCoefficients {
    fn default() -> Self {
        Self {
            dynamic: SoftnessParameters::new(10.0, 30.0).compute_coefficients(1.0 / 60.0),
            non_dynamic: SoftnessParameters::new(10.0, 60.0).compute_coefficients(1.0 / 60.0),
        }
    }
}

fn update_contact_softness(
    mut coefficients: ResMut<ContactSoftnessCoefficients>,
    solver_config: Res<SolverConfig>,
    physics_time: Res<Time<Physics>>,
    substep_time: Res<Time<Substeps>>,
) {
    if solver_config.is_changed() || physics_time.is_changed() || substep_time.is_changed() {
        let dt = physics_time.delta_secs();
        let h = substep_time.delta_secs();

        // The contact frequency should at most be half of the time step due to Nyquist's theorem.
        // https://en.wikipedia.org/wiki/Nyquist%E2%80%93Shannon_sampling_theorem
        let max_hz = 1.0 / (dt * 2.0);
        let hz = solver_config.contact_frequency_factor * max_hz.min(0.25 / h);

        coefficients.dynamic = SoftnessParameters::new(solver_config.contact_damping_ratio, hz)
            .compute_coefficients(h);

        // TODO: Perhaps the non-dynamic softness should be configurable separately.
        // Make contacts against static and kinematic bodies stiffer to avoid clipping through the environment.
        coefficients.non_dynamic =
            SoftnessParameters::new(solver_config.contact_damping_ratio, 2.0 * hz)
                .compute_coefficients(h);
    }
}

/// A resource that stores the contact constraints.
#[derive(Resource, Default, Deref, DerefMut)]
pub struct ContactConstraints(pub Vec<ContactConstraint>);

#[derive(QueryData)]
pub(super) struct BodyQuery {
    pub(super) rb: Read<RigidBody>,
    pub(super) linear_velocity: Read<LinearVelocity>,
    pub(super) index: Option<Read<SolverBodyIndex>>,
}

fn prepare_contact_constraints(
    contact_graph: Res<ContactGraph>,
    constraint_graph: ResMut<ConstraintGraph>,
    mut diagnostics: ResMut<SolverDiagnostics>,
    bodies: Query<BodyQuery, RigidBodyActiveFilter>,
    solver_bodies: Res<SolverBodies>,
    narrow_phase_config: Res<NarrowPhaseConfig>,
    contact_softness: Res<ContactSoftnessCoefficients>,
    mut re_solve_queue: ResMut<ContactReseolveQueue>,
) {
    // The normal preparation pass always rebuilds the complete graph. Any
    // request queued before the solver belongs to the same physics step and
    // is therefore satisfied by this full preparation.
    re_solve_queue.clear_pending();
    let warm_start_enabled = narrow_phase_config.match_contacts;
    prepare_contact_constraints_internal(
        contact_graph,
        constraint_graph,
        &mut diagnostics,
        bodies,
        &solver_bodies,
        contact_softness,
        None,
        warm_start_enabled,
    );
}

fn prepare_contact_constraints_internal(
    contact_graph: Res<ContactGraph>,
    mut constraint_graph: ResMut<ConstraintGraph>,
    diagnostics: &mut SolverDiagnostics,
    bodies: Query<BodyQuery, RigidBodyActiveFilter>,
    solver_bodies: &SolverBodies,
    contact_softness: Res<ContactSoftnessCoefficients>,
    requested_contacts: Option<&[ContactId]>,
    warm_start_enabled: bool,
) {
    let start = crate::utils::Instant::now();

    for color in constraint_graph.colors.iter_mut() {
        if let Some(requested_contacts) = requested_contacts {
            color
                .contact_constraints
                .retain(|constraint| requested_contacts.binary_search(&constraint.contact_id).is_err());
        } else {
            // TODO: Instead of clearing the vector, we could resize it, and just overwrite the old values in the loop below.
            //       Then the inner loop could be parallelized too.
            // TODO: Box2D uses an arena allocator for constraints. Might be worth looking into?
            color.contact_constraints.clear();
        }
    }

    // Get colors with at least one active manifold handle.
    let mut active_colors = constraint_graph
        .colors
        .iter_mut()
        .filter(|color| !color.manifold_handles.is_empty())
        .collect::<Vec<&mut GraphColor>>();

    // Generate contact constraints for each contact pair, parallelizing over graph colors.
    crate::utils::par_for_each(&mut active_colors, 2, |_i, color| {
        for handle in color.manifold_handles.iter() {
            if let Some(requested_contacts) = requested_contacts
                && requested_contacts.binary_search(&handle.contact_id).is_err()
            {
                continue;
            }
            // Get the contact pair and its manifold.
            let contact_pair = contact_graph
                .get_by_id(handle.contact_id)
                .unwrap_or_else(|| {
                    panic!("Contact pair not found in graph: {:?}", handle.contact_id)
                })
                .1;
            let manifold_index = handle.manifold_index;
            let Some(manifold) = contact_pair.manifolds.get(manifold_index) else {
                // A topology owner may have removed a manifold while the
                // status queue is being applied. The stale handle is skipped
                // and will be removed by the next graph synchronization.
                continue;
            };

            if !contact_pair.generates_constraints() {
                continue;
            }

            let (Some(body1_entity), Some(body2_entity)) = (contact_pair.body1, contact_pair.body2)
            else {
                continue;
            };

            // Get the two colliding bodies.
            let Ok(body1) = bodies.get(body1_entity) else {
                continue;
            };
            let Ok(body2) = bodies.get(body2_entity) else {
                continue;
            };

            // TODO: To skip this, we probably shouldn't have manifold handles between non-dynamic bodies
            //       in the constraint graph. Or alternatively, just don't generate contacts at all for them.
            if !body1.rb.is_dynamic() && !body2.rb.is_dynamic() {
                // If both bodies are static or kinematic, skip the contact.
                continue;
            }

            // Look up the solver body indices and inertias, falling back to dummy inertia
            // for static bodies without an associated solver body.
            let index1 = body1.index.copied().unwrap_or(SolverBodyIndex::INVALID);
            let index2 = body2.index.copied().unwrap_or(SolverBodyIndex::INVALID);
            let inertia1 = solver_bodies
                .get_inertia(index1)
                .unwrap_or(&SolverBodyInertia::DUMMY);
            let inertia2 = solver_bodies
                .get_inertia(index2)
                .unwrap_or(&SolverBodyInertia::DUMMY);

            // The ECS velocity components are written back only after the
            // fixed-step solver finishes. During a same-substep topology
            // rebuild, SolverBodies already contains the post-integration and
            // post-rollback velocities and must remain authoritative.
            let linear_velocity1 = solver_bodies
                .get(index1)
                .map_or(body1.linear_velocity.0, |body| body.linear_velocity);
            let linear_velocity2 = solver_bodies
                .get(index2)
                .map_or(body2.linear_velocity.0, |body| body.linear_velocity);

            let constraint = ContactConstraint::generate(
                index1,
                index2,
                contact_pair.body1,
                contact_pair.body2,
                inertia1,
                inertia2,
                linear_velocity1,
                linear_velocity2,
                contact_pair.contact_id,
                manifold,
                manifold_index,
                warm_start_enabled,
                &contact_softness,
            );

            if !constraint.points.is_empty() {
                color.contact_constraints.push(constraint);
            }
        }
    });

    diagnostics.prepare_constraints += start.elapsed();
    diagnostics.contact_constraint_count = constraint_graph
        .colors
        .iter()
        .map(|color| color.contact_constraints.len())
        .sum::<usize>() as u32;
}

/// Returns whether a refreshed pair has a replacement solver manifold for
/// the same rigid-body pair as an old constraint. A contact ID can be retired
/// and reused during topology refresh, so identity alone is not sufficient.
fn has_replacement_solver_manifold(
    pair: Option<&ContactPair>,
    body_entity1: Option<Entity>,
    body_entity2: Option<Entity>,
    manifold_index: usize,
) -> bool {
    pair.is_some_and(|pair| {
        pair.is_touching()
            && pair.generates_constraints()
            && pair.body1 == body_entity1
            && pair.body2 == body_entity2
            && pair
                .manifolds
                .get(manifold_index)
                .is_some_and(|manifold| !manifold.points.is_empty())
    })
}

/// Reverses affected impulses only when refreshed geometry still has a
/// replacement solver manifold for that same body pair.
///
/// If fracture removes the entire contact surface, the old impulse is already
/// a real momentum exchange in this substep. Reversing it with no replacement
/// constraint would erase the impact from both bodies. Such impulses remain
/// committed; surviving contacts are rolled back and re-solved against the
/// refreshed geometry.
///
/// A topology publication may despawn a body; Avian's removal observer
/// swap-removes its solver body immediately. Resolve both indices by entity so
/// a stale slot is never applied to the swapped body.
fn rollback_requested_contact_impulses(
    contact_graph: Res<ContactGraph>,
    mut solver_bodies: ResMut<SolverBodies>,
    mut constraint_graph: ResMut<ConstraintGraph>,
    mut re_solve_queue: ResMut<ContactReseolveQueue>,
    body_indices: Query<&SolverBodyIndex>,
) {
    let Some(requested_contacts) = re_solve_queue.contacts_for_rollback() else {
        return;
    };

    // Snapshot the affected bodies before changing any impulse. This makes
    // the rollback result independently observable from the subsequent re-solve.
    let mut body_velocity_before = HashMap::<Entity, (Vector, Vector)>::new();
    for color in &constraint_graph.colors {
        for constraint in &color.contact_constraints {
            if requested_contacts.binary_search(&constraint.contact_id).is_err() {
                continue;
            }
            for entity in [constraint.body_entity1, constraint.body_entity2]
                .into_iter()
                .flatten()
            {
                let Some(index) = body_indices.get(entity).ok().copied() else {
                    continue;
                };
                if let Some(body) = solver_bodies.get(index) {
                    body_velocity_before.entry(entity).or_insert((
                        body.linear_velocity,
                        body.angular_velocity,
                    ));
                }
            }
        }
    }

    let access = solver_bodies.access();
    let mut matched_constraints = 0usize;
    let mut matched_points = 0usize;
    let mut applied_normal_impulse_ns = 0.0_f64;
    let mut retained_normal_impulse_ns = 0.0_f64;
    let mut replacement_manifolds = 0usize;
    let mut vanished_manifolds = 0usize;

    for color in &mut constraint_graph.colors {
        for constraint in &mut color.contact_constraints {
            if requested_contacts.binary_search(&constraint.contact_id).is_err() {
                continue;
            }
            matched_constraints += 1;
            matched_points += constraint.points.len();

            let normal_impulse_ns = constraint
                .points
                .iter()
                .map(|point| f64::from(point.substep_applied_impulses().0.max(0.0)))
                .sum::<f64>();
            let retained_fraction =
                re_solve_queue.retained_impulse_fraction(constraint.contact_id);

            // A topology publication can despawn a body and make Avian
            // swap-remove another body's solver slot. Refresh both indices
            // BEFORE either the partial-retention or full-rollback operation.
            constraint.body_index1 = constraint
                .body_entity1
                .and_then(|entity| body_indices.get(entity).ok().copied())
                .unwrap_or(SolverBodyIndex::INVALID);
            constraint.body_index2 = constraint
                .body_entity2
                .and_then(|entity| body_indices.get(entity).ok().copied())
                .unwrap_or(SolverBodyIndex::INVALID);

            if let Some(fraction) = retained_fraction {
                constraint.commit_substep_impulse_fraction(fraction, &access);
                applied_normal_impulse_ns += normal_impulse_ns;
                retained_normal_impulse_ns += normal_impulse_ns * f64::from(fraction);
            }

            let replacement = contact_graph
                .get_by_id(constraint.contact_id)
                .map(|(_, pair)| pair);
            let has_replacement = has_replacement_solver_manifold(
                replacement,
                constraint.body_entity1,
                constraint.body_entity2,
                constraint.manifold_index,
            );

            if !has_replacement {
                vanished_manifolds += 1;
                let normal_speed_min = constraint
                    .points
                    .iter()
                    .map(|point| point.normal_speed)
                    .fold(f32::INFINITY, f32::min);
                let normal_speed_max = constraint
                    .points
                    .iter()
                    .map(|point| point.normal_speed)
                    .fold(f32::NEG_INFINITY, f32::max);
                debug!(
                    "CONTACT_IMPULSE_ROLLBACK contact_id={:?} manifold={} body1={:?} body2={:?} normal={:?} normal_speed_min={:.4} normal_speed_max={:.4} points={} normal_impulse_ns={:.3} retained_fraction={} replacement=false",
                    constraint.contact_id,
                    constraint.manifold_index,
                    constraint.body_entity1,
                    constraint.body_entity2,
                    constraint.normal,
                    normal_speed_min,
                    normal_speed_max,
                    constraint.points.len(),
                    normal_impulse_ns,
                    retained_fraction.map_or_else(|| "none".to_owned(), |value| format!("{value:.6}")),
                );
                // No replacement contact means the retained impulse is the
                // only record of this impact. Keep it committed.
                continue;
            }

            replacement_manifolds += 1;
            let normal_speed_min = constraint
                .points
                .iter()
                .map(|point| point.normal_speed)
                .fold(f32::INFINITY, f32::min);
            let normal_speed_max = constraint
                .points
                .iter()
                .map(|point| point.normal_speed)
                .fold(f32::NEG_INFINITY, f32::max);
            constraint.rollback_substep_impulses(&access);
            debug!(
                "CONTACT_IMPULSE_ROLLBACK contact_id={:?} manifold={} body1={:?} body2={:?} normal={:?} normal_speed_min={:.4} normal_speed_max={:.4} points={} normal_impulse_ns={:.3} retained_fraction={} replacement=true",
                constraint.contact_id,
                constraint.manifold_index,
                constraint.body_entity1,
                constraint.body_entity2,
                constraint.normal,
                normal_speed_min,
                normal_speed_max,
                constraint.points.len(),
                normal_impulse_ns,
                retained_fraction.map_or_else(|| "none".to_owned(), |value| format!("{value:.6}")),
            );
        }
    }

    drop(access);
    for (entity, (linear_before, angular_before)) in body_velocity_before {
        let after = body_indices
            .get(entity)
            .ok()
            .copied()
            .and_then(|index| solver_bodies.get(index));
        if let Some(body) = after {
            debug!(
                "CONTACT_ROLLBACK_BODY entity={:?} linear_before={:?} linear_after={:?} delta_linear={:?} angular_before={:?} angular_after={:?} delta_angular={:?}",
                entity,
                linear_before,
                body.linear_velocity,
                body.linear_velocity - linear_before,
                angular_before,
                body.angular_velocity,
                body.angular_velocity - angular_before,
            );
        } else {
            debug!("CONTACT_ROLLBACK_BODY entity={:?} solver_body=missing", entity);
        }
    }

    if matched_constraints == 0 {
        info!(
            "CONTACT_IMPULSE_ROLLBACK_STAGE requested_contacts={} matched_constraints=0",
            requested_contacts.len(),
        );
    } else {
        info!(
            "CONTACT_IMPULSE_ROLLBACK_STAGE requested_contacts={} matched_constraints={} matched_points={} applied_normal_impulse_ns={:.3} retained_normal_impulse_ns={:.3} replacement_manifolds={} vanished_manifolds={}",
            requested_contacts.len(),
            matched_constraints,
            matched_points,
            applied_normal_impulse_ns,
            retained_normal_impulse_ns,
            replacement_manifolds,
            vanished_manifolds,
        );
    }
}

/// Rebuilds only the contact constraints requested by a breakage system.
/// Constraints outside the requested set retain their already-solved impulses
/// and are not rebuilt or solved a second time in this substep.
#[allow(clippy::too_many_arguments)]
fn rebuild_requested_contact_constraints(
    contact_graph: Res<ContactGraph>,
    mut constraint_graph: ResMut<ConstraintGraph>,
    mut diagnostics: ResMut<SolverDiagnostics>,
    bodies: Query<BodyQuery, RigidBodyActiveFilter>,
    solver_bodies: Res<SolverBodies>,
    contact_softness: Res<ContactSoftnessCoefficients>,
    mut re_solve_queue: ResMut<ContactReseolveQueue>,
) {
    let Some(requested_contacts) = re_solve_queue.take_for_rebuild() else {
        return;
    };

    info!(
        "CONTACT_REBUILD_STAGE requested_contacts={}",
        requested_contacts.len(),
    );

    // Solver-body indices are refreshed by entity identity after any
    // fracture-driven body insertion/removal. Impulse rollback already
    // happened before contact-status changes could prune the old constraints.
    for color in &mut constraint_graph.colors {
        for constraint in &mut color.contact_constraints {
            constraint.body_index1 = constraint
                .body_entity1
                .and_then(|entity| bodies.get(entity).ok()?.index.copied())
                .unwrap_or(SolverBodyIndex::INVALID);
            constraint.body_index2 = constraint
                .body_entity2
                .and_then(|entity| bodies.get(entity).ok()?.index.copied())
                .unwrap_or(SolverBodyIndex::INVALID);
        }
    }

    // New geometry starts without cached impulses. The replacement contact
    // receives its response from the actual solver below.
    prepare_contact_constraints_internal(
        contact_graph,
        constraint_graph,
        &mut diagnostics,
        bodies,
        &solver_bodies,
        contact_softness,
        Some(&requested_contacts),
        false,
    );
}

/// Computes the current signed separation using the same body deltas and
/// rotated contact anchors as the velocity solver. The stored offset alone is
/// not the current gap: it must be combined with both anchors and body motion.
fn current_contact_separation(
    stored_separation_offset: f32,
    anchor1: Vector,
    anchor2: Vector,
    normal: Vector,
    body1: Option<&SolverBody>,
    body2: Option<&SolverBody>,
) -> f32 {
    let delta_position1 = body1.map_or(Vector::ZERO, |body| body.delta_position);
    let delta_position2 = body2.map_or(Vector::ZERO, |body| body.delta_position);
    let rotated_anchor1 =
        body1.map_or(anchor1, |body| body.delta_rotation * anchor1);
    let rotated_anchor2 =
        body2.map_or(anchor2, |body| body.delta_rotation * anchor2);

    (delta_position2 - delta_position1 + rotated_anchor2 - rotated_anchor1)
        .dot(normal)
        + stored_separation_offset
}

/// Re-solves the rebuilt contact constraints once after a breakage system has
/// refreshed the affected manifolds. Positions are not integrated a second time.
#[allow(clippy::too_many_arguments)]
fn re_solve_requested_contacts(
    mut solver_bodies: ResMut<SolverBodies>,
    mut constraint_graph: ResMut<ConstraintGraph>,
    solver_config: Res<SolverConfig>,
    length_unit: Res<PhysicsLengthUnit>,
    time: Res<Time>,
    mut diagnostics: ResMut<SolverDiagnostics>,
    mut re_solve_queue: ResMut<ContactReseolveQueue>,
) {
    let Some(requested_contacts) = re_solve_queue.take_prepared_contacts() else {
        return;
    };

    let is_requested = |contact_id: ContactId| {
        requested_contacts.binary_search(&contact_id).is_ok()
    };

    // Record body velocities immediately before the local pass. New
    // constraints have a zero substep impulse ledger, so their ledger after
    // this pass measures only impulse introduced by the re-solve.
    let mut body_velocity_before =
        HashMap::<Entity, (SolverBodyIndex, Vector, Vector)>::new();
    for color in &constraint_graph.colors {
        for constraint in &color.contact_constraints {
            if !is_requested(constraint.contact_id) {
                continue;
            }
            for (entity, index) in [
                (constraint.body_entity1, constraint.body_index1),
                (constraint.body_entity2, constraint.body_index2),
            ] {
                let Some(entity) = entity else {
                    continue;
                };
                if let Some(body) = solver_bodies.get(index) {
                    body_velocity_before.entry(entity).or_insert((
                        index,
                        body.linear_velocity,
                        body.angular_velocity,
                    ));
                }
            }
        }
    }

    let start = crate::utils::Instant::now();
    let solved_constraints = constraint_graph
        .colors
        .iter()
        .flat_map(|color| color.contact_constraints.iter())
        .filter(|constraint| is_requested(constraint.contact_id))
        .count();

    // Unchanged constraints already applied their impulses this substep.
    // Re-solve only the rebuilt contacts, without warm starting them again.
    let access = solver_bodies.access();
    let max_overlap_solve_speed = solver_config.max_overlap_solve_speed * length_unit.0;
    let delta_secs = time.delta_secs();

    // A topology replacement happens after this substep's positions have
    // already been integrated. Newly discovered contacts can begin deeply
    // overlapped because voxel cells were converted into separate rigid bodies
    // at their existing world positions. Applying positional bias a second
    // time turns that representation overlap into an artificial impact.
    // Re-solve only physical velocity constraints; do not apply a second
    // positional-correction pass within the same substep.
    //
    // A topology edit can replace one old manifold with several new manifolds
    // sharing the same impactor. These contacts are born at shared voxel poses
    // and are already representation-overlapped. Repeating the velocity
    // projection on that overlap manufactures a rebound impulse, so the
    // affected island receives one sequential velocity pass after rollback.
    const LOCAL_RE_SOLVE_ITERATIONS: usize = 1;
    for _ in 0..LOCAL_RE_SOLVE_ITERATIONS {
        for constraint in constraint_graph.colors[COLOR_OVERFLOW_INDEX]
            .contact_constraints
            .iter_mut()
        {
            if is_requested(constraint.contact_id) {
                solve_contacts_internal::<false>(
                    &access,
                    constraint,
                    max_overlap_solve_speed,
                    delta_secs,
                );
            }
        }

        for color in constraint_graph
            .colors
            .iter_mut()
            .take(COLOR_OVERFLOW_INDEX)
            .filter(|color| !color.contact_constraints.is_empty())
        {
            crate::utils::par_for_each(&mut color.contact_constraints, 64, |_i, constraint| {
                if is_requested(constraint.contact_id) {
                    solve_contacts_internal::<false>(
                        &access,
                        constraint,
                        max_overlap_solve_speed,
                        delta_secs,
                    );
                }
            });
        }
    }

    drop(access);

    let re_solve_normal_impulse_ns = constraint_graph
        .colors
        .iter()
        .flat_map(|color| color.contact_constraints.iter())
        .filter(|constraint| is_requested(constraint.contact_id))
        .flat_map(|constraint| constraint.points.iter())
        .map(|point| f64::from(point.substep_applied_impulses().0.max(0.0)))
        .sum::<f64>();

    // Keep the re-solve attributable to exact refreshed manifolds. The old
    // manifold index is not a stable identity across narrow-phase refreshes;
    // log the new body pair, normal, approach speed, separations and impulse.
    for color in &constraint_graph.colors {
        for constraint in &color.contact_constraints {
            if !is_requested(constraint.contact_id) {
                continue;
            }
            let normal_impulse_ns = constraint
                .points
                .iter()
                .map(|point| f64::from(point.substep_applied_impulses().0.max(0.0)))
                .sum::<f64>();
            let normal_speed_min = constraint
                .points
                .iter()
                .map(|point| point.normal_speed)
                .fold(f32::INFINITY, f32::min);
            let normal_speed_max = constraint
                .points
                .iter()
                .map(|point| point.normal_speed)
                .fold(f32::NEG_INFINITY, f32::max);
            let body1 = solver_bodies.get(constraint.body_index1);
            let body2 = solver_bodies.get(constraint.body_index2);
            let current_separation_min = constraint
                .points
                .iter()
                .map(|point| {
                    current_contact_separation(
                        point.initial_separation,
                        point.anchor1,
                        point.anchor2,
                        constraint.normal,
                        body1,
                        body2,
                    )
                })
                .fold(f32::INFINITY, f32::min);
            let current_separation_max = constraint
                .points
                .iter()
                .map(|point| {
                    current_contact_separation(
                        point.initial_separation,
                        point.anchor1,
                        point.anchor2,
                        constraint.normal,
                        body1,
                        body2,
                    )
                })
                .fold(f32::NEG_INFINITY, f32::max);
            let stored_offset_min = constraint
                .points
                .iter()
                .map(|point| point.initial_separation)
                .fold(f32::INFINITY, f32::min);
            let stored_offset_max = constraint
                .points
                .iter()
                .map(|point| point.initial_separation)
                .fold(f32::NEG_INFINITY, f32::max);
            let anchors: Vec<_> = constraint
                .points
                .iter()
                .map(|point| (point.anchor1, point.anchor2))
                .collect();
            debug!(
                "CONTACT_RE_SOLVE_MANIFOLD contact_id={:?} manifold={} body1={:?} body2={:?} normal={:?} normal_speed_min={:.4} normal_speed_max={:.4} current_separation_min={:.4} current_separation_max={:.4} stored_offset_min={:.4} stored_offset_max={:.4} points={} normal_impulse_ns={:.3} anchors={:?}",
                constraint.contact_id,
                constraint.manifold_index,
                constraint.body_entity1,
                constraint.body_entity2,
                constraint.normal,
                normal_speed_min,
                normal_speed_max,
                current_separation_min,
                current_separation_max,
                stored_offset_min,
                stored_offset_max,
                constraint.points.len(),
                normal_impulse_ns,
                anchors,
            );
        }
    }

    diagnostics.contact_re_solve_count += 1;
    diagnostics.contact_re_solve += start.elapsed();
    info!(
        "CONTACT_RE_SOLVE_STAGE requested_contacts={} solved_constraints={} re_solve_normal_impulse_ns={:.3} elapsed_ms={:.3}",
        requested_contacts.len(),
        solved_constraints,
        re_solve_normal_impulse_ns,
        start.elapsed().as_secs_f64() * 1_000.0,
    );

    for (entity, (index, linear_before, angular_before)) in body_velocity_before {
        if let Some(body) = solver_bodies.get(index) {
            debug!(
                "CONTACT_RE_SOLVE_BODY entity={:?} linear_before={:?} linear_after={:?} delta_linear={:?} angular_before={:?} angular_after={:?} delta_angular={:?}",
                entity,
                linear_before,
                body.linear_velocity,
                body.linear_velocity - linear_before,
                angular_before,
                body.angular_velocity,
                body.angular_velocity - angular_before,
            );
        } else {
            debug!("CONTACT_RE_SOLVE_BODY entity={:?} solver_body=missing", entity);
        }
    }
}

/// Emits one breakage message per contact pair whose configured normal
/// impulse capacity was exceeded during the current substep.
fn emit_contact_break_events(
    contact_graph: Res<ContactGraph>,
    constraint_graph: Res<ConstraintGraph>,
    mut events: MessageWriter<ContactBreakEvent>,
    mut diagnostics: ResMut<SolverDiagnostics>,
) {
    let mut emitted = Vec::new();

    for color in &constraint_graph.colors {
        for constraint in &color.contact_constraints {
            if emitted.contains(&constraint.contact_id)
                || !constraint
                    .points
                    .iter()
                    .any(|point| point.normal_part.capacity_exceeded)
            {
                continue;
            }

            let Some((_, contact_pair)) = contact_graph.get_by_id(constraint.contact_id) else {
                continue;
            };

            let max_normal_impulse = constraint
                .points
                .iter()
                .map(|point| point.normal_part.max_impulse)
                .fold(f32::INFINITY, f32::min);
            let requested_normal_impulse = constraint
                .points
                .iter()
                .map(|point| point.normal_part.last_requested_impulse)
                .fold(0.0, f32::max);

            events.write(ContactBreakEvent {
                contact_id: constraint.contact_id,
                collider1: contact_pair.collider1,
                collider2: contact_pair.collider2,
                body1: contact_pair.body1,
                body2: contact_pair.body2,
                max_normal_impulse,
                requested_normal_impulse,
                requested_normal_impulse_vector: constraint.normal * requested_normal_impulse,
            });
            emitted.push(constraint.contact_id);
            diagnostics.contact_break_event_count += 1;
        }
    }
}

/// Warm starts the solver by applying the impulses from the previous frame or substep.
///
/// See [`SubstepSolverSystems::WarmStart`] for more information.
fn warm_start(
    mut solver_bodies: ResMut<SolverBodies>,
    mut constraint_graph: ResMut<ConstraintGraph>,
    solver_config: Res<SolverConfig>,
    mut diagnostics: ResMut<SolverDiagnostics>,
) {
    let start = crate::utils::Instant::now();

    let access = solver_bodies.access();

    // Warm start overflow constraints serially. They have lower priority, so they are solved first.
    for constraint in constraint_graph.colors[COLOR_OVERFLOW_INDEX]
        .contact_constraints
        .iter_mut()
    {
        warm_start_internal(&access, constraint, solver_config.warm_start_coefficient);
    }

    // Warm start constraints in each color in parallel.
    for color in constraint_graph
        .colors
        .iter_mut()
        .take(COLOR_OVERFLOW_INDEX)
        .filter(|color| !color.contact_constraints.is_empty())
    {
        crate::utils::par_for_each(&mut color.contact_constraints, 64, |_i, constraint| {
            warm_start_internal(&access, constraint, solver_config.warm_start_coefficient);
        });
    }

    diagnostics.warm_start += start.elapsed();
}

fn warm_start_internal(
    access: &SolverBodiesAccess,
    constraint: &mut ContactConstraint,
    warm_start_coefficient: f32,
) {
    debug_assert!(!constraint.points.is_empty());

    let mut dummy_body1 = SolverBody::DUMMY;
    let mut dummy_body2 = SolverBody::DUMMY;

    let (mut body1, mut inertia1) = (&mut dummy_body1, &SolverBodyInertia::DUMMY);
    let (mut body2, mut inertia2) = (&mut dummy_body2, &SolverBodyInertia::DUMMY);

    // Get the solver bodies for the two colliding bodies. A dummy body is used
    // for static bodies without an associated solver body.
    //
    // SAFETY: Constraint graph coloring guarantees that the two bodies are distinct, and that no
    //         other constraint solved in parallel within this color touches the same bodies.
    let (b1, b2) =
        unsafe { access.get_pair_unchecked_mut(constraint.body_index1, constraint.body_index2) };
    if let Some((body, inertia)) = b1 {
        body1 = body;
        inertia1 = inertia;
    }
    if let Some((body, inertia)) = b2 {
        body2 = body;
        inertia2 = inertia;
    }

    // If a body has a higher dominance, it is treated as a static or kinematic body.
    match constraint.relative_dominance.cmp(&0) {
        Ordering::Greater => inertia1 = &SolverBodyInertia::DUMMY,
        Ordering::Less => inertia2 = &SolverBodyInertia::DUMMY,
        _ => {}
    }

    constraint.warm_start(body1, body2, inertia1, inertia2, warm_start_coefficient);
}

/// Solves contacts by iterating through the given contact constraints
/// and applying impulses to colliding rigid bodies.
///
/// This solve is done `iterations` times. With a substepped solver,
/// `iterations` should typically be `1`, as substeps will handle the iteration.
///
/// If `use_bias` is `true`, the impulses will be boosted to account for overlap.
/// The solver should often be run twice per frame or substep: first with the bias,
/// and then without it to *relax* the velocities and reduce overshooting caused by
/// [warm starting](SubstepSolverSystems::WarmStart).
///
/// See [`SubstepSolverSystems::SolveConstraints`] and [`SubstepSolverSystems::Relax`] for more information.
#[allow(clippy::too_many_arguments)]
#[allow(clippy::type_complexity)]
fn solve_contacts<const USE_BIAS: bool>(
    mut solver_bodies: ResMut<SolverBodies>,
    mut constraint_graph: ResMut<ConstraintGraph>,
    solver_config: Res<SolverConfig>,
    length_unit: Res<PhysicsLengthUnit>,
    time: Res<Time>,
    mut diagnostics: ResMut<SolverDiagnostics>,
) {
    let start = crate::utils::Instant::now();

    let delta_secs = time.delta_secs();
    let max_overlap_solve_speed = solver_config.max_overlap_solve_speed * length_unit.0;

    let access = solver_bodies.access();

    // Solve overflow constraints serially. They have lower priority, so they are solved first.
    for constraint in constraint_graph.colors[COLOR_OVERFLOW_INDEX]
        .contact_constraints
        .iter_mut()
    {
        solve_contacts_internal::<USE_BIAS>(
            &access,
            constraint,
            max_overlap_solve_speed,
            delta_secs,
        );
    }

    // Solve contact constraints in each color in parallel.
    for color in constraint_graph
        .colors
        .iter_mut()
        .take(COLOR_OVERFLOW_INDEX)
        .filter(|color| !color.contact_constraints.is_empty())
    {
        crate::utils::par_for_each(&mut color.contact_constraints, 64, |_i, constraint| {
            solve_contacts_internal::<USE_BIAS>(
                &access,
                constraint,
                max_overlap_solve_speed,
                delta_secs,
            );
        });
    }

    if USE_BIAS {
        diagnostics.solve_constraints += start.elapsed();
    } else {
        diagnostics.relax_velocities += start.elapsed();
    }
}

